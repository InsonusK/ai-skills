scenarios("../features/row-version.feature")

T = TypeVar("T")

SAMPLE_TABLE = """CREATE TABLE notes (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text text NOT NULL
)"""
"""The sample table of the shared scenarios; the application never ships it."""


class _SampleRow(DeclarativeBase):
    """The base of the test's rows, apart from the application's Row, so the
    check of the migrations never sees them."""


class NoteRow(_SampleRow):
    """A row that changes: it declares its version."""

    __tablename__ = "notes"

    id: Mapped[int] = mapped_column(Identity(), primary_key=True)
    text: Mapped[str]
    version: Mapped[str | None] = version_column()


@dataclass(frozen=True)
class EveryNote(Specification[NoteRow]):
    def pick(self, query: Select[NoteRow]) -> Select[NoteRow]:
        return query


@dataclass(frozen=True)
class NoteWithText(Specification[NoteRow]):
    text: str

    def pick(self, query: Select[NoteRow]) -> Select[NoteRow]:
        return query.where(NoteRow.text == self.text)


@dataclass
class World:
    """One scenario: its loop, its database, the repository of notes, the row
    the last step read or wrote, the version it was read with, the two
    callers' rows, the last failure, and the outcome of each race."""

    loop: asyncio.AbstractEventLoop = field(default_factory=asyncio.new_event_loop)
    scenario: postgrestest.ScenarioDatabase | None = None
    database: postgres.Database | None = None
    notes: postgres.Repository[NoteRow] | None = None
    row: NoteRow | None = None
    read_with: str | None = None
    callers: list[NoteRow] = field(default_factory=list)
    error: Exception | None = None
    races: list[int] = field(default_factory=list)

    def run(self, call: Awaitable[T]) -> T:
        return self.loop.run_until_complete(call)

    def attempt(self, call: Awaitable[Any]) -> None:
        try:
            self.run(call)
            self.error = None
        except Exception as error:
            self.error = error
        print(f"when: -> error {self.error!r}")

    def repository(self) -> postgres.Repository[NoteRow]:
        assert self.notes is not None
        return self.notes

    def read(self, text: str) -> NoteRow:
        row = self.run(self.repository().select_by(NoteWithText(text)).single())
        assert row is not None, f"no note {text!r}"
        return row

    def dsn(self) -> str:
        assert self.scenario is not None
        return self.scenario.dsn


async def _other(dsn: str, statement: str, *args: Any) -> Any:
    """Runs statement on a connection of its own, as another client would."""
    connection = await asyncpg.connect(dsn)
    try:
        return await connection.fetchval(statement, *args)
    finally:
        await connection.close()


@pytest.fixture
def world() -> Iterator[World]:
    world = World()
    yield world
    if world.database is not None:
        world.run(world.database.close())
    if world.scenario is not None:
        world.run(world.scenario.drop())
    world.loop.close()


@given("a database with the sample table of notes")
def a_database_with_notes(world: World) -> None:
    world.scenario = world.run(postgrestest.create())
    world.database = postgres.Database(world.scenario.config)
    world.notes = postgres.Repository(world.database, NoteRow)
    world.run(_other(world.dsn(), SAMPLE_TABLE))


@given(parsers.re(r'^the note "(?P<text>[^"]*)"$'))
def the_note(world: World, text: str) -> None:
    world.run(world.repository().insert(NoteRow(text=text)))


@when(parsers.parse('I read the note "{text}"'))
def i_read_the_note(world: World, text: str) -> None:
    world.row = world.read(text)
    world.read_with = world.row.version


@when(parsers.parse('I insert the note "{text}"'))
def i_insert_the_note(world: World, text: str) -> None:
    world.row = NoteRow(text=text)
    world.attempt(world.repository().insert(world.row))
    world.read_with = world.row.version


@when(parsers.parse('I change that row to "{text}" and save it'))
def i_change_that_row(world: World, text: str) -> None:
    assert world.row is not None
    world.row.text = text
    world.attempt(world.repository().update(world.row))


@then("the row should carry a version")
def the_row_should_carry_a_version(world: World) -> None:
    assert world.row is not None and world.row.version, world.row


@then("the row should carry another version than it was read with")
def the_row_should_carry_another_version(world: World) -> None:
    row = world.row
    assert row is not None and row.version and row.version != world.read_with, (row, world.read_with)


@then("no failure should be reported")
def no_failure(world: World) -> None:
    assert world.error is None, world.error


@then("the repository should report a changed row")
def a_changed_row(world: World) -> None:
    assert isinstance(world.error, RowChangedError), world.error


@then(parsers.parse('the note "{text}" should be there for any other connection'))
def the_note_should_be_there(world: World, text: str) -> None:
    assert world.run(_other(world.dsn(), "SELECT count(*) FROM notes WHERE text = $1", text)) == 1


@then(parsers.parse('the note "{text}" should be gone for any other connection'))
def the_note_should_be_gone(world: World, text: str) -> None:
    assert world.run(_other(world.dsn(), "SELECT count(*) FROM notes WHERE text = $1", text)) == 0


@when(parsers.parse('two callers read the note "{text}"'))
def two_callers_read(world: World, text: str) -> None:
    world.callers = [world.read(text), world.read(text)]


@when(parsers.re(r'the (?P<which>first|second) caller saves "(?P<text>[^"]*)"'))
def a_caller_saves(world: World, which: str, text: str) -> None:
    caller = world.callers[0 if which == "first" else 1]
    caller.text = text
    world.attempt(world.repository().update(caller))


@given(parsers.parse('a caller keeps the version of the note "{text}"'))
def a_caller_keeps_the_version(world: World, text: str) -> None:
    world.row = world.read(text)


@given(parsers.parse('another connection changes the note "{text}" to "{to}"'))
@when(parsers.parse('another connection changes the note "{text}" to "{to}"'))
def another_connection_changes(world: World, text: str, to: str) -> None:
    world.run(_other(world.dsn(), "UPDATE notes SET text = $2 WHERE text = $1", text, to))


@when(parsers.parse('the caller saves "{text}" with the version it kept'))
def the_caller_saves_with_the_version_it_kept(world: World, text: str) -> None:
    # Only the id and the version the caller kept: as an API's caller sends
    # them back, with no read in between.
    assert world.row is not None
    world.attempt(world.repository().update(NoteRow(id=world.row.id, text=text, version=world.row.version)))


@when("the caller deletes with the version it kept")
def the_caller_deletes(world: World) -> None:
    assert world.row is not None
    world.attempt(world.repository().delete(NoteRow(id=world.row.id, text=world.row.text, version=world.row.version)))


@when(parsers.parse('I update every note while another connection changes the note "{text}" to "{to}"'))
def i_update_every_note_meanwhile(world: World, text: str, to: str) -> None:
    changed = False

    def change(row: NoteRow) -> None:
        nonlocal changed
        # After the selector read every note, before it saves them: the other
        # client's change runs on its own loop, in a thread, while this one waits.
        if not changed:
            changed = True
            other = threading.Thread(target=lambda: asyncio.run(_other(world.dsn(), "UPDATE notes SET text = $2 WHERE text = $1", text, to)))
            other.start()
            other.join()
        row.text += " (updated)"

    world.attempt(world.repository().select_by(EveryNote()).update(change))


@when(parsers.parse("two callers save one row at the same moment, {times:d} times"))
def two_callers_race(world: World, times: int) -> None:
    async def race() -> int:
        read = await world.repository().select_by(NoteWithText("a")).single()
        assert read is not None
        mine = [NoteRow(id=read.id, text="a", version=read.version) for _ in range(2)]
        outcomes = await asyncio.gather(*(world.repository().update(row) for row in mine), return_exceptions=True)
        for outcome in outcomes:
            if isinstance(outcome, BaseException) and not isinstance(outcome, RowChangedError):
                raise outcome
        return sum(1 for outcome in outcomes if isinstance(outcome, RowChangedError))

    world.races = [world.run(race()) for _ in range(times)]


@then("every time exactly one of them should have been told a changed row")
def exactly_one_each_time(world: World) -> None:
    assert world.races and all(changed == 1 for changed in world.races), world.races


@then("every mapped row should be marked as changing or as never changing")
def every_row_is_marked(world: World) -> None:
    for mapper in Row.registry.mappers:
        row = mapper.class_
        assert version_attribute(mapper) is not None or issubclass(row, NeverChanges), (
            f"the row {row.__name__} declares no version_column() and is no NeverChanges"
        )
