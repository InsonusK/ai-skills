"""The sample tables of the shared scenarios, owners and tasks, which the
application never ships: their rows, keys, specifications, and a repository
of a table's own with methods past the contract. They have a declarative base
of their own, so the check of the migrations never sees them."""

from dataclasses import dataclass

from sqlalchemy import ForeignKey, Select, text
from sqlalchemy.dialects.postgresql import insert
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from todo.infrastructure.postgres import Columns, Database, Key, Projection, Repository, Specification

SCHEMA = [
    """CREATE TABLE owners (
        id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name text NOT NULL UNIQUE
    )""",
    """CREATE TABLE tasks (
        id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        owner_id bigint  NOT NULL REFERENCES owners (id),
        title    text    NOT NULL,
        done     boolean NOT NULL,
        UNIQUE (owner_id, title)
    )""",
]


class Sample(DeclarativeBase):
    """The base of the sample rows, apart from the application's."""


class OwnerRow(Sample):
    __tablename__ = "owners"

    id: Mapped[int] = mapped_column(primary_key=True)
    name: Mapped[str]


class TaskRow(Sample):
    __tablename__ = "tasks"

    id: Mapped[int] = mapped_column(primary_key=True)
    owner_id: Mapped[int] = mapped_column(ForeignKey("owners.id"))
    title: Mapped[str]
    done: Mapped[bool]
    owner: Mapped[OwnerRow] = relationship()


@dataclass
class OwnerAndTitle:
    """A task's title with its owner's name: the result of a projection."""

    owner: str
    title: str


TaskTitle: Key[TaskRow] = Key(TaskRow.title)
TaskOwner: Key[TaskRow] = Key(TaskRow.owner_id)
ResultTitle: Key[OwnerAndTitle] = Key(TaskRow.title)


@dataclass(frozen=True)
class UnclosedTasks(Specification[TaskRow]):
    """The open tasks of the owner named owner: a join along the relation."""

    owner: str

    def pick(self, query: Select[TaskRow]) -> Select[TaskRow]:
        return query.join(TaskRow.owner).where(OwnerRow.name == self.owner, TaskRow.done.is_(False))


class OpenTasks(Specification[TaskRow]):
    """Every open task."""

    def pick(self, query: Select[TaskRow]) -> Select[TaskRow]:
        return query.where(TaskRow.done.is_(False))


@dataclass(frozen=True)
class TaskById(Specification[TaskRow]):
    id: int

    def pick(self, query: Select[TaskRow]) -> Select[TaskRow]:
        return query.where(TaskRow.id == self.id)


@dataclass(frozen=True)
class TaskByTitle(Specification[TaskRow]):
    title: str

    def pick(self, query: Select[TaskRow]) -> Select[TaskRow]:
        return query.where(TaskRow.title == self.title)


@dataclass(frozen=True)
class TitlesWithOwners(Projection[TaskRow, OwnerAndTitle]):
    """The titles of the owner named owner, with the owner's name."""

    owner: str

    def pick(self, query: Select[TaskRow]) -> Columns:
        return (
            query.join(TaskRow.owner)
            .where(OwnerRow.name == self.owner)
            .with_only_columns(OwnerRow.name.label("owner"), TaskRow.title)
        )


class WithPage(Specification[TaskRow]):
    """A specification the contract refuses: it holds a page."""

    def pick(self, query: Select[TaskRow]) -> Select[TaskRow]:
        return query.limit(1)


class WithOrder(Specification[TaskRow]):
    """A specification the contract refuses: it holds an order."""

    def pick(self, query: Select[TaskRow]) -> Select[TaskRow]:
        return query.order_by(TaskRow.title)


class TaskRepository(Repository[TaskRow]):
    """The repository of tasks with two methods past the contract, each
    through Statements.run, as a table's own repository writes them."""

    def __init__(self, database: Database) -> None:
        super().__init__(database, TaskRow)

    async def insert_unless_there(self, owner_id: int, title: str) -> None:
        """An upsert: a task already there stays as it is."""

        async def run(session: AsyncSession) -> None:
            await session.execute(
                insert(TaskRow).values(owner_id=owner_id, title=title, done=False).on_conflict_do_nothing()
            )

        await self.run("upsert into tasks", run)

    async def rename(self, title: str, to: str) -> None:
        """A bulk statement: every task titled title is renamed to."""

        async def run(session: AsyncSession) -> None:
            await session.execute(text("UPDATE tasks SET title = :to WHERE title = :title"), {"to": to, "title": title})

        await self.run("rename in tasks", run)

    async def fail_with(self, state: str) -> None:
        """A statement the database answers with the failure state."""

        async def run(session: AsyncSession) -> None:
            await session.execute(text(f"DO $$ BEGIN RAISE EXCEPTION 'asked' USING ERRCODE = '{state}'; END $$"))

        await self.run("fail", run)
