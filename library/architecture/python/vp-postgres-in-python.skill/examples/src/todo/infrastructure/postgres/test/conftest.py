def check_rows(world: World) -> None:
    """alembic check over the migrated database: a row no migration matches
    raises AutogenerateDiffsDetected."""
    assert world.database is not None
    config = alembic_config(migrations.LOCATION)

    def check(connection: Connection) -> None:
        config.attributes["connection"] = connection
        command.check(config)

    async def run() -> None:
        assert world.database is not None
        async with world.database.engine().connect() as connection:
            await connection.run_sync(check)

    world.attempt(run())


@then("every row of the application should match its table")
def every_row_should_match(world: World) -> None:
    check_rows(world)
    assert world.error is None, f"the check found: {world.error}"


@then("the check of the rows should fail")
def the_check_should_fail(world: World) -> None:
    check_rows(world)
    assert isinstance(world.error, AutogenerateDiffsDetected), f"the check answered {world.error!r}"


