@dataclass
class World:
    """One scenario: its event loop, its database once a step creates one, the
    repositories over it, and what the last step answered."""

    monkeypatch: pytest.MonkeyPatch
    loop: asyncio.AbstractEventLoop = field(default_factory=asyncio.new_event_loop)
    scenario: postgrestest.ScenarioDatabase | None = None
    database: Database | None = None
    tasks: TaskRepository | None = None
    owners: postgres.Repository[OwnerRow] | None = None
    titles: Projections[TaskRow, OwnerAndTitle] | None = None
    selector: Selector[TaskRow] | None = None
    ordered: OrderedSelector[TaskRow] | None = None
    second: OrderedSelector[TaskRow] | None = None
    results: ResultSelector[OwnerAndTitle] | None = None
    row: TaskRow | None = None
    inserted: TaskRow | None = None
    answer: Any = None
    error: Exception | None = None
    config: Config | None = None

    def run(self, call: Awaitable[T]) -> T:
        """Runs call on the scenario's loop: the pool of a database lives on
        the loop that opened its connections."""
        return self.loop.run_until_complete(call)

    def attempt(self, call: Awaitable[Any]) -> Any:
        """Runs call, keeping its answer or its failure."""
        try:
            self.answer = self.run(call)
        except Exception as error:
            self.error = error
            self.answer = None
        print(f"answer: {self.answer!r}, error: {self.error!r}")
        return self.answer

    def create(self) -> postgrestest.ScenarioDatabase:
        self.scenario = self.run(postgrestest.create())
        self.open(self.scenario.config)
        return self.scenario

    def open(self, config: Config, pool_size: int = 5, max_overflow: int = 10) -> None:
        if self.database is not None:
            self.run(self.database.close())
        self.database = Database(config, pool_size=pool_size, max_overflow=max_overflow)
        self.tasks = TaskRepository(self.database)
        self.owners = postgres.Repository(self.database, OwnerRow)
        self.titles = Projections(self.database, TaskRow, OwnerAndTitle)

    def other(self, statement: str, *args: Any) -> Any:
        """Runs statement on a connection of its own, outside the repository's
        pool, and answers its first value."""
        assert self.scenario is not None

        async def run() -> Any:
            connection = await asyncpg.connect(self.scenario.dsn)  # type: ignore[union-attr]
            try:
                return await connection.fetchval(statement, *args)
            finally:
                await connection.close()

        return self.run(run())

    def owner_id(self, name: str) -> int:
        return int(self.other("SELECT id FROM owners WHERE name = $1", name))


@pytest.fixture
def world(monkeypatch: pytest.MonkeyPatch) -> Iterator[World]:
    monkeypatch.delenv("DATABASE_DSN", raising=False)
    monkeypatch.delenv("MIGRATE_ON_START", raising=False)
    world = World(monkeypatch)
    yield world
    if world.database is not None:
        world.run(world.database.close())
    if world.scenario is not None:
        world.run(world.scenario.drop())
    world.loop.close()


def cells(row: Any, header: list[str]) -> list[str]:
    """The fields the header names, read from the row object, as the table
    writes them."""
    values = [getattr(row, name) for name in header]
    return [("true" if value else "false") if isinstance(value, bool) else str(value) for value in values]


def expect_rows(rows: Any, datatable: list[list[str]]) -> None:
    header, expected = datatable[0], datatable[1:]
    assert isinstance(rows, list), f"the answer is {rows!r}, not a list"
    got = [cells(row, header) for row in rows]
    assert got == expected, f"rows {got}, want {expected}"


def expect_one(row: Any, datatable: list[list[str]]) -> None:
    header, expected = datatable[0], datatable[1:]
    assert row is not None and not isinstance(row, list), f"the answer is {row!r}, not one row"
    assert [cells(row, header)] == expected, f"row {cells(row, header)}, want {expected}"


