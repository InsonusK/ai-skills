@given(parsers.re(r'an unusable DATABASE_DSN holding "(?P<text>[^"]*)"'))
def an_unusable_dsn(world: World, text: str) -> None:
    world.monkeypatch.setenv("DATABASE_DSN", f"not a connection string {text}")


@given(parsers.re(r'the environment variable "(?P<name>[^"]*)" is "(?P<value>[^"]*)"'))
def the_environment_variable(world: World, name: str, value: str) -> None:
    world.monkeypatch.setenv(name, value)


@when("the settings are loaded")
def the_settings_are_loaded(world: World) -> None:
    try:
        world.config = postgres.load_config()
    except ValueError as error:
        world.error = error


@then(parsers.re(r'the application should migrate on start: "(?P<switch>true|false)"'))
def migrate_on_start(world: World, switch: str) -> None:
    assert world.config is not None, f"loading failed: {world.error!r}"
    assert world.config.migrate_on_start is (switch == "true")


@then(parsers.re(r'the settings printed should not mention "(?P<text>[^"]*)"'))
def the_settings_printed(world: World, text: str) -> None:
    assert world.config is not None
    for printed in (str(world.config), repr(world.config), f"{world.config}", f"{world.config!r}"):
        assert text not in printed, printed


@then(parsers.re(r'loading should fail mentioning "(?P<text>[^"]*)"'))
def loading_should_fail(world: World, text: str) -> None:
    assert isinstance(world.error, ValueError) and text in str(world.error), f"loading answered {world.error!r}"


@then(parsers.re(r'the failure should not mention "(?P<text>[^"]*)"'))
def the_failure_should_not_mention(world: World, text: str) -> None:
    assert world.error is not None
    # The whole traceback a log would print, causes and contexts included.
    printed = "".join(traceback.format_exception(world.error))
    assert text not in printed, printed


@then(parsers.re(r'the database should be "(?P<database>[^"]*)" on "(?P<host>[^"]*)"'))
def the_database_should_be(world: World, database: str, host: str) -> None:
    assert world.config is not None, f"loading failed: {world.error!r}"
    assert (world.config.url().database, world.config.url().host) == (database, host)
