#!/usr/bin/env python3
"""Print tracked example deltas and same-base intersections for attach review."""
from collections import defaultdict
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[4]
tracked = subprocess.check_output(
    ['git', 'ls-files', '-z', 'library/architecture'], cwd=ROOT,
).decode().split('\0')
files = {p for p in tracked if p and (ROOT / p).is_file()}
groups = defaultdict(list)


def relative_files(directory):
    prefix = directory + '/'
    return {p.removeprefix(prefix) for p in files if p.startswith(prefix)}


for name in sorted(files):
    path = Path(name)
    if path.suffix != '.allow' or len(path.parts) != 5:
        continue
    directives = [line.split(maxsplit=1) for line in (ROOT / path).read_text().splitlines()
                  if line.strip() and not line.lstrip().startswith('#')]
    base = next(value for kind, value in directives if kind == 'base')
    example = str(path.parent / next(
        (value for kind, value in directives if kind == 'examples'), 'examples'))
    before, after = relative_files(base), relative_files(example)
    changed = {p for p in before & after
               if (ROOT / base / p).read_bytes() != (ROOT / example / p).read_bytes()}
    groups[base].append((name, example, after - before, changed, before - after))

print('# Attach delta inventory\n')
print('Generated by `python3 library/architecture/agent/attach-rule/inventory.py`.\n')
print('Tracked files only; paths are relative to the named base/example. '
      'Intersections are candidates for review, not a proof of compatibility.\n')
print(f'{sum(map(len, groups.values()))} allow files; {len(groups)} distinct bases.\n')
for base, variants in sorted(groups.items()):
    print(f'## `{base}`\n')
    changed_by, added_by, deleted_by = defaultdict(list), defaultdict(list), defaultdict(list)
    for allow, example, added, changed, deleted in variants:
        label = str(Path(allow).relative_to('library/architecture'))
        print(f'### `{label}`\n')
        print(f'Example: `{example}`; added {len(added)}, changed {len(changed)}, '
              f'deleted {len(deleted)}.\n')
        for title, paths in [('Changed', changed), ('Deleted', deleted)]:
            print(f'{title}: ' + (', '.join(f'`{p}`' for p in sorted(paths)) or 'none') + '.\n')
        for paths, target in [(changed, changed_by), (added, added_by), (deleted, deleted_by)]:
            for p in paths:
                target[p].append((label, example))
    print('### Same-base intersections\n')
    count = 0
    for p in sorted(changed_by.keys() | added_by.keys() | deleted_by.keys()):
        edits = changed_by[p] + deleted_by[p]
        additions = added_by[p]
        if len(edits) > 1:
            print(f'- Changed/deleted `{p}`: ' + ', '.join(f'`{a}`' for a, _ in edits) + '.')
            count += 1
        if len(additions) > 1:
            identical = len({(ROOT / ex / p).read_bytes() for _, ex in additions}) == 1
            print(f'- Added `{p}` ({"identical" if identical else "different"}): '
                  + ', '.join(f'`{a}`' for a, _ in additions) + '.')
            count += 1
    if not count:
        print('None.')
    print()
