using Ardalis.Specification;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Postgres.Abstractions;
using Postgres.Abstractions.Rows;
using Postgres.Repositories;
using Postgres.Testing;
using Reqnroll;
using Xunit;
using Xunit.Abstractions;

namespace Postgres.Tests.Steps;

// The table of the shared scenarios of skill vp-row-version: notes, whose rows
// change. It exists only in this project: the application never ships it.

/// <summary>A row that changes: it carries its row version.</summary>
public sealed class NoteRow
{
    public long Id { get; set; }
    public required string Text { get; set; }
    public uint Version { get; set; }
}

public sealed class NotesContext(DbContextOptions<NotesContext> options) : DbContext(options)
{
    protected override void OnModelCreating(ModelBuilder model) =>
        model.Entity<NoteRow>(row =>
        {
            row.ToTable("notes");
            row.Property(note => note.Id).HasColumnName("id");
            row.Property(note => note.Text).HasColumnName("text");
            row.Property(note => note.Version).IsRowVersion();
        });
}

public sealed class EveryNote : Specification<NoteRow>;

public sealed class NoteWithText : Specification<NoteRow>
{
    public NoteWithText(string text) => Query.Where(note => note.Text == text);
}

/// <summary>
/// The steps of row-version.feature (a copy never edited) on the base repository
/// of vp-postgres-in-dotnet, which EF Core makes compare the row version. Scoped to
/// the feature: its "no failure", "changed row" steps win over the repository's.
/// </summary>
[Binding]
[Scope(Feature = "The version of a row")]
public sealed class RowVersionSteps(ITestOutputHelper output) : IAsyncDisposable
{
    private TestDatabase? _database;
    private readonly List<NotesContext> _contexts = [];
    private NoteRow? _row;
    private uint _readWith;
    private readonly List<NoteRow> _callers = [];
    private Exception? _error;
    private readonly List<int> _races = [];

    // A repository over a context of its own, as one command scope has.
    private PostgresRepository<NoteRow> Notes()
    {
        var context = new NotesContext(new DbContextOptionsBuilder<NotesContext>().UseNpgsql(_database!.Dsn).Options);
        _contexts.Add(context);
        return new PostgresRepository<NoteRow>(context);
    }

    private async Task AttemptAsync(Func<Task> call)
    {
        try
        {
            await call();
            _error = null;
        }
        catch (Exception error)
        {
            _error = error;
        }
        output.WriteLine($"when: -> {_error?.GetType().Name ?? "ok"} {_error?.Message}");
    }

    private async Task<NoteRow> ReadAsync(string text) =>
        await Notes().SelectBy(new NoteWithText(text)).SingleAsync(CancellationToken.None) ?? throw new InvalidOperationException($"no note {text}");

    private async Task OtherAsync(string sql, params object[] values)
    {
        await using var connection = new NpgsqlConnection(_database!.Dsn);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand(sql, connection);
        foreach (var value in values)
        {
            command.Parameters.AddWithValue(value);
        }
        await command.ExecuteNonQueryAsync();
    }

    private async Task<long> CountAsync(string text)
    {
        await using var connection = new NpgsqlConnection(_database!.Dsn);
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand("SELECT count(*) FROM notes WHERE text = $1", connection);
        command.Parameters.AddWithValue(text);
        return (long)(await command.ExecuteScalarAsync())!;
    }

    [Given("a database with the sample table of notes")]
    public async Task GivenADatabaseWithNotes()
    {
        _database = await TestDatabase.CreateAsync();
        await OtherAsync("CREATE TABLE notes (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, text text NOT NULL)");
    }

    [Given("the note {string}")]
    public Task GivenTheNote(string text) => Notes().InsertAsync(new NoteRow { Text = text }, CancellationToken.None);

    [When("I read the note {string}")]
    public async Task WhenIReadTheNote(string text)
    {
        _row = await ReadAsync(text);
        _readWith = _row.Version;
    }

    [When("I insert the note {string}")]
    public async Task WhenIInsertTheNote(string text)
    {
        _row = new NoteRow { Text = text };
        await AttemptAsync(() => Notes().InsertAsync(_row, CancellationToken.None));
        _readWith = _row.Version;
    }

    [When("I change that row to {string} and save it")]
    public Task WhenIChangeThatRow(string text)
    {
        _row!.Text = text;
        return AttemptAsync(() => Notes().UpdateAsync(_row, CancellationToken.None));
    }

    [Then("the row should carry a version")]
    public void ThenTheRowShouldCarryAVersion() => Assert.NotEqual(0u, _row!.Version);

    [Then("the row should carry another version than it was read with")]
    public void ThenAnotherVersion() => Assert.NotEqual(_readWith, _row!.Version);

    [Then("no failure should be reported")]
    public void ThenNoFailure() => Assert.Null(_error);

    [Then("the repository should report a changed row")]
    public void ThenAChangedRow() => Assert.IsType<RowChangedException>(_error);

    [Then("the note {string} should be there for any other connection")]
    public async Task ThenTheNoteShouldBeThere(string text) => Assert.Equal(1, await CountAsync(text));

    [Then("the note {string} should be gone for any other connection")]
    public async Task ThenTheNoteShouldBeGone(string text) => Assert.Equal(0, await CountAsync(text));

    [When("two callers read the note {string}")]
    public async Task WhenTwoCallersRead(string text)
    {
        _callers.Add(await ReadAsync(text));
        _callers.Add(await ReadAsync(text));
    }

    [When("the first caller saves {string}")]
    public Task WhenTheFirstCallerSaves(string text) => CallerSavesAsync(0, text);

    [When("the second caller saves {string}")]
    public Task WhenTheSecondCallerSaves(string text) => CallerSavesAsync(1, text);

    private Task CallerSavesAsync(int caller, string text)
    {
        _callers[caller].Text = text;
        return AttemptAsync(() => Notes().UpdateAsync(_callers[caller], CancellationToken.None));
    }

    [Given("a caller keeps the version of the note {string}")]
    public async Task GivenACallerKeepsTheVersion(string text) => _row = await ReadAsync(text);

    [Given("another connection changes the note {string} to {string}")]
    [When("another connection changes the note {string} to {string}")]
    public Task WhenAnotherConnectionChanges(string text, string to) => OtherAsync("UPDATE notes SET text = $2 WHERE text = $1", text, to);

    // Only the id and the version the caller kept: as an API's caller sends them
    // back, with no read in between.
    [When("the caller saves {string} with the version it kept")]
    public Task WhenTheCallerSaves(string text) =>
        AttemptAsync(() => Notes().UpdateAsync(new NoteRow { Id = _row!.Id, Text = text, Version = _row.Version }, CancellationToken.None));

    [When("the caller deletes with the version it kept")]
    public Task WhenTheCallerDeletes() =>
        AttemptAsync(() => Notes().DeleteAsync(new NoteRow { Id = _row!.Id, Text = _row.Text, Version = _row.Version }, CancellationToken.None));

    [When("I update every note while another connection changes the note {string} to {string}")]
    public Task WhenIUpdateEveryNoteMeanwhile(string text, string to)
    {
        var changed = false;
        return AttemptAsync(() => Notes().SelectBy(new EveryNote()).UpdateAsync(row =>
        {
            // After the selector read every note, before it saves them.
            if (!changed)
            {
                changed = true;
                OtherAsync("UPDATE notes SET text = $2 WHERE text = $1", text, to).GetAwaiter().GetResult();
            }
            row.Text += " (updated)";
        }, CancellationToken.None));
    }

    [When("two callers save one row at the same moment, {int} times")]
    public async Task WhenTwoCallersRace(int times)
    {
        for (var i = 0; i < times; i++)
        {
            var read = await ReadAsync("a");
            var saves = Enumerable.Range(0, 2)
                .Select(_ => Notes().UpdateAsync(new NoteRow { Id = read.Id, Text = "a", Version = read.Version }, CancellationToken.None))
                .ToList();
            var changed = 0;
            foreach (var save in saves)
            {
                try
                {
                    await save;
                }
                catch (RowChangedException)
                {
                    changed++;
                }
            }
            _races.Add(changed);
        }
    }

    [Then("every time exactly one of them should have been told a changed row")]
    public void ThenExactlyOneEachTime() => Assert.All(_races, changed => Assert.Equal(1, changed));

    [Then("every mapped row should be marked as changing or as never changing")]
    public void ThenEveryRowIsMarked()
    {
        using var context = new AppDbContext(new DbContextOptionsBuilder<AppDbContext>().UseNpgsql("Host=unused").Options);
        foreach (var row in context.Model.GetEntityTypes())
        {
            var versioned = row.GetProperties().Any(property => property.IsConcurrencyToken && property.ValueGenerated == Microsoft.EntityFrameworkCore.Metadata.ValueGenerated.OnAddOrUpdate);
            Assert.True(versioned || typeof(INeverChanges).IsAssignableFrom(row.ClrType),
                $"the row {row.ClrType.Name} has no row version and is no INeverChanges");
        }
    }

    public async ValueTask DisposeAsync()
    {
        foreach (var context in _contexts)
        {
            await context.DisposeAsync();
        }
        if (_database is not null)
        {
            await _database.DisposeAsync();
        }
    }
}
