// Package test runs the shared scenarios of skill vp-row-version
// (../features, a copy never edited) on a table of notes this test makes:
// the version a row declares, compared by the base repository.
package test

import (
	"context"
	"errors"
	"fmt"
	"reflect"
	"sync"

	"github.com/cucumber/godog"
	"github.com/jackc/pgx/v5"
	"gorm.io/gorm"

	"github.com/example/todo/internal/infrastructure/postgres"
	"github.com/example/todo/internal/infrastructure/postgres/postgrestest"
	"github.com/example/todo/internal/infrastructure/postgres/tables"
)

func logf(format string, args ...any) { fmt.Printf(format+"\n", args...) }

// The sample table of the shared scenarios; the application never ships it.
const sampleTable = `CREATE TABLE notes (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text text NOT NULL
)`

// NoteRow is a row that changes: it declares its version.
type NoteRow struct {
	ID      int64 `gorm:"primaryKey"`
	Text    string
	Version postgres.Version `gorm:"column:xmin;->;-:migration"`
}

func (NoteRow) TableName() string { return "notes" }

// everyNote picks every note.
type everyNote struct {
	postgres.SpecificationOf[NoteRow]
}

func (everyNote) Pick(query *gorm.DB) *gorm.DB { return query }

// noteWithText picks the note of one text.
type noteWithText struct {
	postgres.SpecificationOf[NoteRow]
	Text string
}

func (s noteWithText) Pick(query *gorm.DB) *gorm.DB { return query.Where("text = ?", s.Text) }

// world is one scenario: its database, the repository of notes, the row the
// last step read or wrote, the version a caller kept, and the last failure.
type world struct {
	database *postgrestest.Database
	db       *postgres.Database
	notes    *postgres.Repository[NoteRow]
	row      NoteRow
	readWith postgres.Version
	callers  [2]NoteRow
	err      error
	// races are how many of two saves at once were told a changed row, per race.
	races []int
}

func registerSteps(sc *godog.ScenarioContext) {
	w := &world{}
	sc.Before(func(ctx context.Context, _ *godog.Scenario) (context.Context, error) {
		*w = world{}
		return ctx, nil
	})
	sc.After(func(ctx context.Context, _ *godog.Scenario, err error) (context.Context, error) {
		if w.db != nil {
			_ = w.db.Close()
		}
		if w.database != nil {
			return ctx, w.database.Drop(ctx)
		}
		return ctx, nil
	})

	sc.Step(`^a database with the sample table of notes$`, func(ctx context.Context) error {
		database, err := postgrestest.Create(ctx)
		if err != nil {
			return err
		}
		w.database = database
		if w.db, err = postgres.Open(database.Config); err != nil {
			return err
		}
		w.notes = postgres.NewRepository[NoteRow](w.db)
		return w.other(ctx, sampleTable)
	})
	sc.Step(`^the note "([^"]*)"$`, func(ctx context.Context, text string) error {
		return w.notes.Insert(ctx, &NoteRow{Text: text})
	})
	sc.Step(`^I read the note "([^"]*)"$`, func(ctx context.Context, text string) error {
		row, err := w.read(ctx, text)
		w.row, w.readWith = row, row.Version
		return err
	})
	sc.Step(`^I insert the note "([^"]*)"$`, func(ctx context.Context, text string) error {
		w.row = NoteRow{Text: text}
		w.err = w.notes.Insert(ctx, &w.row)
		w.readWith = w.row.Version
		return nil
	})
	sc.Step(`^I change that row to "([^"]*)" and save it$`, func(ctx context.Context, text string) error {
		w.row.Text = text
		w.err = w.notes.Update(ctx, &w.row)
		logf("when: update to %q -> version %q err=%v", text, w.row.Version, w.err)
		return nil
	})
	sc.Step(`^the row should carry a version$`, func() error {
		if w.row.Version == "" {
			return fmt.Errorf("the row %+v carries no version", w.row)
		}
		return nil
	})
	sc.Step(`^the row should carry another version than it was read with$`, func() error {
		if w.row.Version == "" || w.row.Version == w.readWith {
			return fmt.Errorf("the row carries the version %q, read with %q", w.row.Version, w.readWith)
		}
		return nil
	})
	sc.Step(`^no failure should be reported$`, func() error { return w.err })
	sc.Step(`^the repository should report a changed row$`, func() error {
		if !errors.Is(w.err, postgres.ErrRowChanged) {
			return fmt.Errorf("the repository reported %v, want a changed row", w.err)
		}
		return nil
	})
	sc.Step(`^the note "([^"]*)" should be there for any other connection$`, func(ctx context.Context, text string) error {
		var n int
		err := w.query(ctx, func(conn *pgx.Conn) error {
			return conn.QueryRow(ctx, "SELECT count(*) FROM notes WHERE text = $1", text).Scan(&n)
		})
		if err == nil && n != 1 {
			return fmt.Errorf("%d notes %q for another connection, want one", n, text)
		}
		return err
	})
	sc.Step(`^the note "([^"]*)" should be gone for any other connection$`, func(ctx context.Context, text string) error {
		var n int
		err := w.query(ctx, func(conn *pgx.Conn) error {
			return conn.QueryRow(ctx, "SELECT count(*) FROM notes WHERE text = $1", text).Scan(&n)
		})
		if err == nil && n != 0 {
			return fmt.Errorf("%d notes %q for another connection, want none", n, text)
		}
		return err
	})
	sc.Step(`^two callers read the note "([^"]*)"$`, func(ctx context.Context, text string) error {
		for i := range w.callers {
			row, err := w.read(ctx, text)
			if err != nil {
				return err
			}
			w.callers[i] = row
		}
		return nil
	})
	sc.Step(`^the (first|second) caller saves "([^"]*)"$`, func(ctx context.Context, which, text string) error {
		caller := &w.callers[map[string]int{"first": 0, "second": 1}[which]]
		caller.Text = text
		w.err = w.notes.Update(ctx, caller)
		return nil
	})
	sc.Step(`^a caller keeps the version of the note "([^"]*)"$`, func(ctx context.Context, text string) error {
		row, err := w.read(ctx, text)
		w.row = row
		return err
	})
	sc.Step(`^another connection changes the note "([^"]*)" to "([^"]*)"$`, func(ctx context.Context, from, to string) error {
		return w.other(ctx, "UPDATE notes SET text = $2 WHERE text = $1", from, to)
	})
	sc.Step(`^the caller saves "([^"]*)" with the version it kept$`, func(ctx context.Context, text string) error {
		// Only the id and the version the caller kept: as an API's caller
		// sends them back, with no read in between.
		row := NoteRow{ID: w.row.ID, Text: text, Version: w.row.Version}
		w.err = w.notes.Update(ctx, &row)
		return nil
	})
	sc.Step(`^the caller deletes with the version it kept$`, func(ctx context.Context) error {
		row := NoteRow{ID: w.row.ID, Version: w.row.Version}
		w.err = w.notes.Delete(ctx, &row)
		return nil
	})
	sc.Step(`^I update every note while another connection changes the note "([^"]*)" to "([^"]*)"$`, func(ctx context.Context, from, to string) error {
		var once sync.Once
		_, w.err = w.notes.SelectBy(everyNote{}).Update(ctx, func(row *NoteRow) {
			// After the selector read every note, before it saves them.
			once.Do(func() {
				if err := w.other(ctx, "UPDATE notes SET text = $2 WHERE text = $1", from, to); err != nil {
					panic(err)
				}
			})
			row.Text += " (updated)"
		})
		return nil
	})
	sc.Step(`^two callers save one row at the same moment, (\d+) times$`, func(ctx context.Context, times int) error {
		for range times {
			row, err := w.read(ctx, "a")
			if err != nil {
				return err
			}
			errs := make([]error, 2)
			var start, done sync.WaitGroup
			start.Add(1)
			for i := range errs {
				done.Add(1)
				go func(mine NoteRow) {
					defer done.Done()
					start.Wait()
					mine.Text = "a"
					errs[i] = w.notes.Update(ctx, &mine)
				}(row)
			}
			start.Done()
			done.Wait()
			changed := 0
			for _, err := range errs {
				switch {
				case errors.Is(err, postgres.ErrRowChanged):
					changed++
				case err != nil:
					return err
				}
			}
			w.races = append(w.races, changed)
		}
		return nil
	})
	sc.Step(`^every time exactly one of them should have been told a changed row$`, func() error {
		for i, changed := range w.races {
			if changed != 1 {
				return fmt.Errorf("race %d: %d of two saves were told a changed row, want exactly one", i+1, changed)
			}
		}
		return nil
	})
	sc.Step(`^every mapped row should be marked as changing or as never changing$`, func() error {
		for _, row := range tables.Rows {
			if !declaresVersion(row) {
				if _, ok := row.(tables.NeverChanges); !ok {
					return fmt.Errorf("the row %T declares no postgres.Version and is no tables.NeverChanges", row)
				}
			}
		}
		return nil
	})
}

// declaresVersion tells a row with a field of type postgres.Version.
func declaresVersion(row any) bool {
	t := reflect.TypeOf(row)
	for i := range t.NumField() {
		if t.Field(i).Type == reflect.TypeOf(postgres.Version("")) {
			return true
		}
	}
	return false
}

func (w *world) read(ctx context.Context, text string) (NoteRow, error) {
	row, err := w.notes.SelectBy(noteWithText{Text: text}).Single(ctx)
	if err != nil || row == nil {
		return NoteRow{}, fmt.Errorf("read the note %q: %v", text, err)
	}
	return *row, nil
}

// other runs statement on a connection of its own, as another client would.
func (w *world) other(ctx context.Context, statement string, args ...any) error {
	return w.query(ctx, func(conn *pgx.Conn) error {
		_, err := conn.Exec(ctx, statement, args...)
		return err
	})
}

func (w *world) query(ctx context.Context, run func(conn *pgx.Conn) error) error {
	conn, err := pgx.Connect(ctx, w.database.DSN)
	if err != nil {
		return err
	}
	defer conn.Close(ctx)
	return run(conn)
}
