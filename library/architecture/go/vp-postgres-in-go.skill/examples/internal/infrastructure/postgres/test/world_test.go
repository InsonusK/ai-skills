// The sample tables of the shared scenarios: owners, and their tasks, a
// title unique per owner. They live only in this test; the application never
// ships them.
const sampleTables = `
CREATE TABLE owners (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL UNIQUE
);
CREATE TABLE tasks (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint  NOT NULL REFERENCES owners (id),
    title    text    NOT NULL,
    done     boolean NOT NULL,
    UNIQUE (owner_id, title)
);`

type OwnerRow struct {
	ID   int64 `gorm:"primaryKey"`
	Name string
}

func (OwnerRow) TableName() string { return "owners" }

// TaskRow has its owner as a relation, so the scenarios show that a write of
// a task never writes its owner.
type TaskRow struct {
	ID      int64 `gorm:"primaryKey"`
	OwnerID int64
	Owner   *OwnerRow
	Title   string
	Done    bool
}

func (TaskRow) TableName() string { return "tasks" }

// OwnerAndTitle is the result of a projection over tasks and their owners.
type OwnerAndTitle struct {
	Owner string
	Title string
}

var (
	TaskTitle   = postgres.KeyOf[TaskRow]("title")
	TaskOwner   = postgres.KeyOf[TaskRow]("owner_id")
	ResultTitle = postgres.KeyOf[OwnerAndTitle]("title")
)

const ofOwner = "JOIN owners ON owners.id = tasks.owner_id"

// UnclosedTasks picks the open tasks of one owner, along the relation.
type UnclosedTasks struct {
	postgres.SpecificationOf[TaskRow]
	Owner string
}

func (s UnclosedTasks) Pick(query *gorm.DB) *gorm.DB {
	return query.Joins(ofOwner).Where("owners.name = ? AND NOT tasks.done", s.Owner)
}

// OpenTasks picks every open task.
type OpenTasks struct {
	postgres.SpecificationOf[TaskRow]
}

func (OpenTasks) Pick(query *gorm.DB) *gorm.DB { return query.Where("NOT tasks.done") }

// TaskByID picks the task of a unique key.
type TaskByID struct {
	postgres.SpecificationOf[TaskRow]
	ID int64
}

func (s TaskByID) Pick(query *gorm.DB) *gorm.DB { return query.Where("tasks.id = ?", s.ID) }

// TaskByTitle picks the tasks of a title; the scenarios give every task a
// title of its own.
type TaskByTitle struct {
	postgres.SpecificationOf[TaskRow]
	Title string
}

func (s TaskByTitle) Pick(query *gorm.DB) *gorm.DB { return query.Where("tasks.title = ?", s.Title) }

// TitlesWithOwners answers the title of every task of one owner with the
// owner's name, a column of the related table.
type TitlesWithOwners struct {
	postgres.ProjectionOf[TaskRow, OwnerAndTitle]
	Owner string
}

func (s TitlesWithOwners) Pick(query *gorm.DB) *gorm.DB {
	return query.Joins(ofOwner).Where("owners.name = ?", s.Owner).Select("owners.name AS owner, tasks.title")
}

// WithPage and WithOrder break the rule of a specification: the repository
// refuses them.
type WithPage struct {
	postgres.SpecificationOf[TaskRow]
}

func (WithPage) Pick(query *gorm.DB) *gorm.DB { return query.Limit(2) }

type WithOrder struct {
	postgres.SpecificationOf[TaskRow]
}

func (WithOrder) Pick(query *gorm.DB) *gorm.DB { return query.Order("title") }

type ownerByName struct {
	postgres.SpecificationOf[OwnerRow]
	Name string
}

func (s ownerByName) Pick(query *gorm.DB) *gorm.DB { return query.Where("name = ?", s.Name) }

// TaskRepository is the table's own repository: the contract, and the
// statements it cannot express, each through Run.
type TaskRepository struct {
	*postgres.Repository[TaskRow]
}

// InsertUnlessThere is an upsert: a task already there stays as it is.
func (r TaskRepository) InsertUnlessThere(ctx context.Context, row TaskRow) error {
	_, err := r.Run(ctx, "insert into tasks unless there", func(session *gorm.DB) *gorm.DB {
		return session.Exec(`INSERT INTO tasks (owner_id, title, done) VALUES (?, ?, ?)
			ON CONFLICT (owner_id, title) DO NOTHING`, row.OwnerID, row.Title, row.Done)
	})
	return err
}

// Rename renames every task of a title in one statement.
func (r TaskRepository) Rename(ctx context.Context, from, to string) (int64, error) {
	return r.Run(ctx, "rename tasks", func(session *gorm.DB) *gorm.DB {
		return session.Exec("UPDATE tasks SET title = ? WHERE title = ?", to, from)
	})
}

// FailWith makes the database answer a failure of the code state.
func (r TaskRepository) FailWith(ctx context.Context, state string) error {
	_, err := r.Run(ctx, "fail", func(session *gorm.DB) *gorm.DB {
		return session.Exec(fmt.Sprintf("DO $$ BEGIN RAISE EXCEPTION 'asked for' USING ERRCODE = '%s'; END $$", state))
	})
	return err
}

// world is one scenario: a database of its own, the pool over it, the last
// selector and what the last call answered.
type world struct {
	database *postgrestest.Database
	db       *postgres.Database
	tasks    TaskRepository
	owners   *postgres.Repository[OwnerRow]
	titles   *postgres.Projections[TaskRow, OwnerAndTitle]

	selector postgres.Selector[TaskRow]
	ordered  postgres.OrderedSelector[TaskRow]
	results  postgres.ResultSelector[OwnerAndTitle]
	ordering postgres.OrderedResultSelector[OwnerAndTitle]
	second   postgres.Selector[TaskRow]
	apart    [2]postgres.OrderedSelector[TaskRow]
	row      *TaskRow
	written  int64
	err      error

	env    map[string]*string
	config postgres.Config
}

// open opens the pool over cfg and the repositories over it.
func (w *world) open(cfg postgres.Config) error {
	if w.db != nil {
		_ = w.db.Close()
	}
	db, err := postgres.Open(cfg)
	if err != nil {
		return err
	}
	w.db = db
	w.tasks = TaskRepository{postgres.NewRepository[TaskRow](db)}
	w.owners = postgres.NewRepository[OwnerRow](db)
	w.titles = postgres.NewProjections[TaskRow, OwnerAndTitle](db)
	return nil
}

// create creates the scenario's database and opens the pool over it.
func (w *world) create(ctx context.Context) error {
	database, err := postgrestest.Create(ctx)
	if err != nil {
		return err
	}
	w.database = database
	return w.open(database.Config)
}

// other runs run on a connection of its own, as another client would.
func (w *world) other(ctx context.Context, run func(conn *pgx.Conn) error) error {
	conn, err := pgx.Connect(ctx, w.database.DSN)
	if err != nil {
		return err
	}
	defer conn.Close(ctx)
	return run(conn)
}

func (w *world) ownerID(ctx context.Context, name string) (int64, error) {
	owner, err := w.owners.SelectBy(ownerByName{Name: name}).Single(ctx)
	if err != nil {
		return 0, err
	}
	if owner == nil {
		return 0, fmt.Errorf("no owner %q", name)
	}
	return owner.ID, nil
}

// setenv sets a variable for the scenario; restoreEnv puts the old value back.
func (w *world) setenv(name, value string) {
	if _, saved := w.env[name]; !saved {
		if old, ok := os.LookupEnv(name); ok {
			w.env[name] = &old
		} else {
			w.env[name] = nil
		}
	}
	os.Setenv(name, value)
}

func (w *world) restoreEnv() {
	for name, value := range w.env {
		if value == nil {
			os.Unsetenv(name)
		} else {
			os.Setenv(name, *value)
		}
	}
}
